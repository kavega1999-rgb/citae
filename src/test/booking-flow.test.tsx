import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { BookingSteps } from '@/features/booking/booking-steps';
import { proofExtension, localDate } from '@/features/booking/booking-utils';
import { supabase } from '@/integrations/supabase/client';
vi.mock('@/integrations/supabase/client',()=>({supabase:{rpc:vi.fn()}}));
vi.mock('@/features/notifications/push.functions',()=>({notifyNewBooking:vi.fn(()=>Promise.resolve(true))}));
vi.mock('@tanstack/react-start',()=>({useServerFn:vi.fn(),createServerFn:()=>({inputValidator:()=>({handler:()=>vi.fn()})})}));
afterEach(()=>{cleanup();vi.clearAllMocks();});
const settings={business_name:'Test only',timezone:'America/Bogota',currency:'COP',deposit_percentage:30,buffer_minutes:15,hold_minutes:60,payment_instructions:null,nequi_number:'test',daviplata_number:null,bank_name:null,account_type:null,account_number:null,account_holder:null,requires_deposit:true,cancellation_policy:''};
const slot={slot_start:'2026-11-12T14:00:00Z',slot_end:'2026-11-12T14:45:00Z',total_amount:25000,total_duration_minutes:45};
function mockRpc(pros:unknown[],created?:unknown){vi.mocked(supabase.rpc).mockImplementation(((name:string)=>Promise.resolve({data:name==='get_public_professionals'?pros:name==='get_available_slots'?[slot]:[created],error:null})) as never);}
describe('booking flow',()=>{
 it('does not request availability when active professionals cannot perform the selected services',async()=>{
  vi.mocked(supabase.rpc).mockImplementation(((name:string,args:Record<string,unknown>)=>Promise.resolve({data:name==='get_public_professionals'&&!args['p_service_ids']?[{id:'pro-1',full_name:'Professional',photo_path:null}]:[],error:null})) as never);
  const client=new QueryClient({defaultOptions:{queries:{retry:false}}});
  render(<QueryClientProvider client={client}><BookingSteps slug="consultorio" stage="date" ids={['service-1']} settings={settings} onBack={vi.fn()} onCreated={vi.fn()} onTime={vi.fn()}/></QueryClientProvider>);
  await waitFor(()=>expect(supabase.rpc).toHaveBeenCalledWith('get_public_professionals',{p_business_slug:'consultorio'}));
  await waitFor(()=>expect(screen.getByLabelText('Fecha')).toBeDisabled());
  fireEvent.change(screen.getByLabelText('Fecha'),{target:{value:'2026-11-17'}});
  expect(supabase.rpc).not.toHaveBeenCalledWith('get_available_slots',expect.anything());
 });
 it('does not automatically retry a rejected availability request',async()=>{
  vi.mocked(supabase.rpc).mockImplementation(((name:string)=>Promise.resolve({data:[],error:name==='get_available_slots'?{message:'Unavailable',code:'P0001'}:null})) as never);
  const client=new QueryClient({defaultOptions:{queries:{retry:3,retryDelay:1}}});
  render(<QueryClientProvider client={client}><BookingSteps slug="consultorio" stage="date" ids={['service-1']} settings={settings} onBack={vi.fn()} onCreated={vi.fn()} onTime={vi.fn()}/></QueryClientProvider>);
  await waitFor(()=>expect(screen.getByLabelText('Fecha')).not.toBeDisabled());
  fireEvent.change(screen.getByLabelText('Fecha'),{target:{value:'2026-11-17'}});
  await screen.findByRole('alert');
  await new Promise(r=>setTimeout(r,30));
  expect(vi.mocked(supabase.rpc).mock.calls.filter(([name])=>name==='get_available_slots')).toHaveLength(1);
 });
 it('requires choosing a professional when the business has them and books with that professional',async()=>{
  const created={appointment_id:'test-id',payment_id:'p',payment_amount:7500,total_amount:25000,payment_deadline_at:'2026-11-12T15:00:00Z',access_token:'a'.repeat(64)};
  mockRpc([{id:'pro-1',full_name:'Profesional de prueba',specialty:null,photo_path:null,display_order:0}],created);
  const onCreated=vi.fn(),client=new QueryClient({defaultOptions:{queries:{retry:false}}});
  const props={slug:'consultorio',ids:['real-service-id'],settings,onBack:vi.fn(),onCreated,onTime:vi.fn()};
  const view=render(<QueryClientProvider client={client}><BookingSteps stage="date" {...props}/></QueryClientProvider>);
  await screen.findByRole('button',{name:/Profesional de prueba/});
  fireEvent.change(screen.getByLabelText('Fecha'),{target:{value:'2026-11-12'}});
  await new Promise(r=>setTimeout(r,20));
  expect(supabase.rpc).not.toHaveBeenCalledWith('get_available_slots',expect.anything());
  fireEvent.click(screen.getByRole('button',{name:/Profesional de prueba/}));
  fireEvent.click(await screen.findByRole('button',{name:/9:00/}));
  expect(supabase.rpc).toHaveBeenCalledWith('get_available_slots',expect.objectContaining({p_professional_id:'pro-1'}));
  view.rerender(<QueryClientProvider client={client}><BookingSteps stage="details" {...props}/></QueryClientProvider>);
  fireEvent.change(screen.getByLabelText('Nombre completo'),{target:{value:'Test client'}});
  fireEvent.change(screen.getByLabelText('Teléfono'),{target:{value:'test-phone'}});
  fireEvent.click(screen.getByRole('radio',{name:'Nequi'}));
  fireEvent.submit(screen.getByRole('button',{name:'Crear reserva'}).closest('form') as HTMLFormElement);
  await waitFor(()=>expect(onCreated).toHaveBeenCalledWith(created));
  expect(supabase.rpc).toHaveBeenLastCalledWith('create_public_appointment_v2',expect.objectContaining({p_professional_id:'pro-1'}));
 });
 it('creates bookings only through v2 with the selected actual slot and service IDs',async()=>{
  const created={appointment_id:'test-id',payment_id:'test-payment',payment_amount:7500,total_amount:25000,payment_deadline_at:'2026-11-12T15:00:00Z',access_token:'a'.repeat(64)};
  mockRpc([],created);
  const onCreated=vi.fn(),client=new QueryClient({defaultOptions:{queries:{retry:false}}});
  const props={slug:'consultorio',ids:['real-service-id'],settings,onBack:vi.fn(),onCreated,onTime:vi.fn()};
  const view=render(<QueryClientProvider client={client}><BookingSteps stage="date" {...props}/></QueryClientProvider>);
  fireEvent.change(screen.getByLabelText('Fecha'),{target:{value:'2026-11-12'}});
  await waitFor(()=>expect(screen.getByRole('button',{name:/9:00/})).toBeInTheDocument());
  fireEvent.click(screen.getByRole('button',{name:/9:00/}));
  view.rerender(<QueryClientProvider client={client}><BookingSteps stage="details" {...props}/></QueryClientProvider>);
  fireEvent.change(screen.getByLabelText('Nombre completo'),{target:{value:'Test client'}});
  fireEvent.change(screen.getByLabelText('Teléfono'),{target:{value:'test-phone'}});
  fireEvent.click(screen.getByRole('radio',{name:'Nequi'}));
  fireEvent.submit(screen.getByRole('button',{name:'Crear reserva'}).closest('form') as HTMLFormElement);
  await waitFor(()=>expect(onCreated).toHaveBeenCalledWith(created));
  expect(supabase.rpc).toHaveBeenLastCalledWith('create_public_appointment_v2',expect.objectContaining({p_business_slug:'consultorio',p_service_ids:['real-service-id'],p_start_at:'2026-11-12T14:00:00Z',p_payment_method:'nequi'}));
  expect(supabase.rpc).toHaveBeenCalledWith('get_available_slots',expect.objectContaining({p_business_slug:'consultorio',p_service_ids:['real-service-id']}));
 });
 it('skips the payment method when the business does not require a deposit',async()=>{
  const created={appointment_id:'id',payment_id:null,payment_amount:0,total_amount:25000,payment_deadline_at:null,access_token:'a'.repeat(64)};
  mockRpc([],created);
  const onCreated=vi.fn(),client=new QueryClient({defaultOptions:{queries:{retry:false}}});
  const props={slug:'consultorio',ids:['s'],settings:{...settings,requires_deposit:false},onBack:vi.fn(),onCreated,onTime:vi.fn()};
  const view=render(<QueryClientProvider client={client}><BookingSteps stage="date" {...props}/></QueryClientProvider>);
  fireEvent.change(screen.getByLabelText('Fecha'),{target:{value:'2026-11-12'}});
  fireEvent.click(await screen.findByRole('button',{name:/9:00/}));
  view.rerender(<QueryClientProvider client={client}><BookingSteps stage="details" {...props}/></QueryClientProvider>);
  expect(screen.queryByText('Medio de pago del anticipo')).toBeNull();
  fireEvent.change(screen.getByLabelText('Nombre completo'),{target:{value:'Test'}});
  fireEvent.change(screen.getByLabelText('Teléfono'),{target:{value:'300'}});
  fireEvent.submit(screen.getByRole('button',{name:'Crear reserva'}).closest('form') as HTMLFormElement);
  await waitFor(()=>expect(onCreated).toHaveBeenCalledWith(created));
 });
 it('uses the business timezone for dates',()=>{expect(localDate('America/Bogota',new Date('2026-11-12T02:00:00Z'))).toBe('2026-11-11');});
 it('accepts only supported proof types',()=>{expect(proofExtension({type:'image/jpeg',size:100})).toBe('jpg');expect(()=>proofExtension({type:'text/html',size:100})).toThrow();});
 it('rejects files exceeding 5 MB',()=>{expect(()=>proofExtension({type:'application/pdf',size:5*1024*1024+1})).toThrow();});
});
